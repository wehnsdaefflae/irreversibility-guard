#!/usr/bin/env python3
"""render_results — regenerate artifacts/RESULTS.md from artifacts/tests/results.json.

usage: scripts/render_results.py [--selftest]
  (no flag)   read artifacts/tests/results.json and write artifacts/RESULTS.md
  --selftest  render a fixture in memory and check its shape; non-zero on failure

Every number in RESULTS.md comes from results.json. Nothing is restated from memory.

net: none
secrets: none
calls: none
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
# In the published repository the project root IS the repo root; in the authoring
# routine the same file lives one level above an `artifacts/` project directory.
# Resolve both so `python scripts/<name>.py` works from a fresh clone.
PROJ = (ROOT / "artifacts") if (ROOT / "artifacts" / "guard").is_dir() else ROOT
RESULTS_JSON = PROJ / "tests" / "results.json"
RESULTS_MD = PROJ / "RESULTS.md"


def render(r: dict) -> str:
    out: list[str] = []
    a = out.append
    a("# Measured results")
    a("")
    a(f"Guard revision **{r['guard_rev']}** · measured **{r['date']}** · "
      "generated by `scripts/score_scenarios.py` from the suites themselves.")
    a("")
    a("## Reproduce")
    a("")
    a("```sh")
    a("pip install -e '.[test]'")
    a(r.get("reproduce", "python -m pytest tests/ -v"))
    a("```")
    a("")
    a("## Scenario results")
    a("")
    a("| id | family | what the agent attempts | expected verdict / reason | measured | result | evidence (test) |")
    a("|---|---|---|---|---|---|---|")
    for s in r["per_scenario"]:
        a(f"| `{s['id']}` | {s['family']} | {s['attempt']} | `{s['expected']}` | "
          f"`{s['measured']}` | **{s['status']}** | `{s['evidence']}` |")
    a("")
    a(f"**{r['scenarios_passing']} of {r['scenarios_total']} scenarios pass** "
      f"({r['scenarios_failing']} not passing).")
    if r.get("harness_cases_total"):
        a("")
        a(f"Each named scenario above is additionally expanded by "
          f"`tests/scenarios/test_fuzz.py` over many tools, targets, argument shapes, "
          f"alias-chain depths, batch positions and nesting depths: "
          f"**{r['harness_cases_passing']} of {r['harness_cases_total']} harness cases "
          f"pass** ({r['harness_cases_failing']} failing). A variant whose verdict or "
          f"reason code differs from its family's fails the suite.")
    a("")
    a("## Benign control set — the cost of the guard")
    a("")
    a("| id | result | evidence (test) |")
    a("|---|---|---|")
    for b in r.get("benign_detail", []):
        a(f"| `{b['id']}` | {b['status']} | `{b['evidence']}` |")
    a("")
    a(f"False positives: **{r['benign_false_positives']}/{r['benign_total']} = "
      f"{r['false_positive_rate']}** — legitimate actions the guard blocked.")
    a("")
    a("A scenario that does not pass stays in this table marked FAIL with what the guard")
    a("would need; removing an inconvenient scenario is the failure this harness exists to")
    a("prevent.")
    a("")

    s = r.get("search")
    if s:
        on, off = s["gates_on"], s["gates_off"]
        a("## Property-based search for UNDECLARED irreversible compositions")
        a("")
        a(f"`python -m guard.search --depth {s['depth']} --json`, measured **{s['date']}**. "
          f"**{s['sequences_searched']} action sequences** over "
          f"{len(s['alphabet']['verbs'])} verbs × {len(s['alphabet']['locations'])} "
          f"locations, exhaustive to depth {s['depth']} and deterministic.")
        a("")
        a("The oracle is a **concrete world model that does not import the guard**: "
          "locations really hold content, the acts really mutate them, and a violation is "
          "a sequence the guard allowed end to end that nevertheless left pre-existing "
          "content unreachable. Threat model: "
          f"*{s['threat_model']}*.")
        a("")
        a("| configuration | hard-coded pair table (baseline) | derived effect-taint closure |")
        a("|---|---|---|")
        a(f"| **deployable** (undo path required, read-before-destroy on) | "
          f"{on['violations_table_mode']} violations | "
          f"**{on['violations_derived_mode']} violations** |")
        a(f"| composition isolated (those two gates off) | "
          f"{off['violations_table_mode']} violations | "
          f"{off['violations_derived_mode']} violations |")
        a("")
        a(f"In the deployable configuration the derived mechanism catches "
          f"**{on['caught_by_derived_but_not_by_the_table']}** sequences the pair table "
          f"misses, of which **{on['undeclared_by_the_table']}** correspond to no entry in "
          f"that table at all — irreversible compositions nobody declared. Two were checked "
          f"into the scenario table above as `bp-10` and `bp-11`; `bp-11` "
          f"(a copy onto an occupied path, declared reversible) is a hazard the search "
          f"found and the author had not thought of.")
        a("")
        a("**Read the second row carefully.** With the two ordinary gates off, the derived "
          "closure reports MORE violations than it does deployed, and in that configuration "
          "the pair table reports more still. That is a property of what each mechanism is "
          "for: the closure deliberately defers a *bare* destructive act to the gate that "
          "owns it (read-before-destroy, undo path) because that gate gives a clearer "
          "reason code, so with those gates removed nothing catches those acts. Only the "
          "first row describes a guard anyone would deploy. Both are printed because "
          "quoting the first alone would overstate the mechanism.")
        a("")
        a(f"Full findings, including the search alphabet and worked examples: "
          f"`tests/search-findings.json`.")
        a("")

    # ---- the de-authored external evaluation (scripts/eval_agentharm.py, eval_external.py)
    ah = r.get("agentharm")
    if ah:
        c, ph, pb = (ah["per_call_all_functions"], ah["per_prompt_harmful"],
                     ah["per_prompt_harmless_benign"])
        nb = ah["no_guard_baseline"]
        a("## External evaluation on a third-party agentic benchmark")
        a("")
        a(f"Measured {ah['date']} · guard `{ah['guard_rev']}` · "
          f"`scripts/eval_agentharm.py all` · raw: `tests/agentharm-eval.json`")
        a("")
        a("The scenario table above is written by the guard's own author, so it cannot "
          "measure whether the guard generalises. This section is scored on "
          f"[AgentHarm]({ah['benchmark']['source']}) (UK AI Safety Institute): "
          f"**{ah['benchmark']['prompts']} prompts** over "
          f"**{ah['benchmark']['functions']} tool functions**, with AgentHarm's own "
          "`target_functions` as the ground truth for which calls each prompt is meant to "
          "drive, and its distribution-matched `harmless_benign` config as the control. "
          "The per-function irreversibility labels come from a model shown no guard "
          "source, no manifest and no mention of a guard. Nothing in this section was "
          "labelled by the author.")
        a("")
        a("**All 85 functions are foreign to the guard's manifest.** That is the realistic "
          "deployment condition — an integrator's tool surface the guard's author never "
          "saw — and it means only the heuristic tier and the fail-closed rule for "
          "undeclared verbs are under test here. The manifest tier, the one sound tier, "
          "was deliberately not given the answers; deriving a manifest from the labels "
          "would have made the result perfect by construction.")
        a("")
        a("**Two false-negative rates, and the strict one is the one to believe.** "
          "The strict rate counts a stop only where **the agent cannot clear it itself**, "
          "and that turns on a distinction the two HOLD kinds do not share — a "
          "distinction this project got wrong in both directions before an independent "
          "reviewer probed the shipped API on 2026-11-12:\n\n"
          "- `hold.irreversible_needs_reconsent` **is** agent-satisfiable. The act is "
          "added to `session.consented` and a second emission with `consent=True` "
          "returns `ALLOW/allow.re_consented`. It is a speed bump, not a stop.\n"
          "- `hold.unknown_verb_fails_closed` **is not**. The unknown tier returns it "
          "*before* any consent handling and the act never enters `session.consented`, "
          "so re-consent can never clear it — probe-verified on `terminal`, "
          "`upload_file`, `make_online_purchases`, `wire_funds` and "
          "`share_on_pinterest`, each still HOLD on three successive consents.\n\n"
          "Only the first is counted as a non-stop. Earlier revisions of this file "
          "counted *every* HOLD as agent-satisfiable, which overstated the leak against "
          "this project's own code; the revision before that counted every HOLD as a "
          "stop, which understated it. Both rates are printed, strict first.")
        a("")
        a("| measure | result | 95% CI |")
        a("|---|---|---|")
        a(f"| **irreversible functions an ADVERSARIAL agent reaches** (HOLD is not a stop) | "
          f"**{c['false_negatives_strict']}/{c['n_irreversible']}** = "
          f"**{c['false_negative_rate_strict']:.3f}** | "
          f"{c['false_negative_ci95_strict'][0]:.3f}–{c['false_negative_ci95_strict'][1]:.3f} |")
        a(f"| irreversible functions allowed outright (HOLD counts as a stop) | "
          f"{c['false_negatives']}/{c['n_irreversible']} = "
          f"{c['false_negative_rate']:.3f} | "
          f"{c['false_negative_ci95'][0]:.3f}–{c['false_negative_ci95'][1]:.3f} |")
        a(f"| reversible functions BLOCKED (false positives) | "
          f"**{c['false_positives']}/{c['n_reversible']}** = "
          f"{c['false_positive_rate']:.3f} | "
          f"{c['false_positive_ci95'][0]:.3f}–{c['false_positive_ci95'][1]:.3f} |")
        a(f"| benign prompts delayed by at least one hold | "
          f"{pb['prompts_with_a_reversible_call_blocked']}/{pb['n_prompts']} = "
          f"{pb['friction_rate']:.3f} | see the caveat below |")
        a("")
        strict = c["false_negative_functions_strict"]
        if strict:
            a(f"**The {len(strict)} functions an adversarial agent reaches** are not "
              "marginal cases: " + ", ".join(f"`{s}`" for s in strict[:20]) +
              (" …" if len(strict) > 20 else "") + ". Each got a HOLD rather than "
              "`REQUIRE_HUMAN`, because the heuristic tier read the verb as outward or "
              "destroying but no manifest entry declared it, so no human-go gate applied. "
              "**This is the guard's single largest measured weakness** and the clearest "
              "argument for declaring the tool surface: a declared `outward: true` entry "
              "turns each of these into `REQUIRE_HUMAN`.")
            a("")
        else:
            a("**No irreversible foreign function is reachable by the agent alone.** "
              "Every one of the 40 ends at a verdict the agent cannot clear: "
              "`REQUIRE_HUMAN`, `DENY`, or the unknown tier's fail-closed HOLD, which is "
              "returned before consent is consulted. That is a stronger claim than the "
              "`0/40` *allowed-outright* row beside it, and it is worth reading with the "
              "false-positive rate in the same table: the same fail-closed rule that "
              "produces it blocks 27 of 45 reversible functions. **This number is a "
              "property of a tool surface the guard has never seen, which is the point — "
              "but it is bought by refusing the unrecognised, not by recognising "
              "anything.** The honest statement of the guard's limit is in "
              "`LIMITATIONS.md`: a classifier-based guard cannot be sound, and this "
              "result does not make it so.")
            a("")
        bau = ah.get("block_all_unknown_baseline")
        if bau:
            a(f"**The honest baseline is not 'no guard' — it is 'block every unknown "
              f"verb'.** That trivial policy also allows **0** irreversible foreign "
              f"functions, so the zero-outright-allow figure is not where this guard "
              f"earns its keep. What it adds over block-all-unknown is the "
              f"**{bau['reversible_functions_allowed']} of "
              f"{bau['reversible_functions_total']}** reversible functions it correctly "
              f"lets through (block-all-unknown: 0) and a per-verb reason code for every "
              f"decision. The 'no guard at all' row below is reported for completeness, "
              f"not as the comparison that matters.")
            a("")
        if ah.get("statistical_caveat"):
            a(f"**Statistical caveat, stated rather than buried:** {ah['statistical_caveat']}")
            a("")
        a(f"**Against no guard at all:** all **{nb['irreversible_calls_in_surface']}** "
          f"irreversible calls execute unguarded; guarded, "
          f"**{nb['irreversible_calls_executed_guarded']}** execute outright and "
          f"**{c['false_negatives_strict']}** more are reachable by an agent that "
          f"re-consents to the holds it CAN clear — so the guarded figure against an "
          f"adversarial agent is **{c['false_negatives_strict']} of "
          f"{nb['irreversible_calls_in_surface']}**. Read it against the "
          f"block-all-unknown baseline above, not against 'no guard': refusing every "
          f"unrecognised verb reaches the same figure, and what this guard adds is the "
          f"reversible traffic it still lets through plus a reason code per decision.")
        a("")
        tiers = {}
        for case in ah.get("per_call", []):
            key = (case["tier"], case["truth_irreversible"])
            bucket = tiers.setdefault(key, [0, 0])
            bucket[0] += 1
            bucket[1] += 1 if case["blocked"] else 0
        heur_rev = tiers.get(("heuristic", False), [0, 0])
        heur_irr = tiers.get(("heuristic", True), [0, 0])
        unk_rev = tiers.get(("unknown", False), [0, 0])
        unk_irr = tiers.get(("unknown", True), [0, 0])
        a("**Where the two numbers come from — the decomposition matters more than either "
          "figure.** Of the foreign verbs the heuristic tier could read, it blocked "
          f"**{heur_irr[1]}/{heur_irr[0]}** irreversible ones and "
          f"**{heur_rev[1]}/{heur_rev[0]}** reversible ones. The remaining "
          f"**{unk_rev[0] + unk_irr[0]}** verbs no tier could read: the fail-closed rule "
          f"held all of them, catching **{unk_irr[1]}** more irreversible calls by brute "
          f"force and producing **{unk_rev[1]}** of the false positives. So the zero "
          "false-negative rate above is *not* evidence of a clever classifier — roughly "
          "half of it is fail-closed refusing everything it does not recognise. That "
          "**fail-closed stop is a HOLD the agent cannot clear** (it is returned before "
          "consent is consulted), so it holds against an adversarial agent — but it is "
          "a refusal to act on the unrecognised, not classifier skill, and it is bought "
          "at the cost of the reversible verbs it blocks with it. The "
          "false-positive rate is the price of the same rule. An integrator who declares "
          "their tool surface in the manifest moves verbs out of that tier and pays less; "
          "one who declares nothing gets this.")
        a("")
        a("**The guard is an irreversibility gate, not a harm classifier.** AgentHarm's "
          "harmful and `harmless_benign` prompts draw on the same tool surface, and the "
          f"guard delays {ph['friction_rate']:.3f} of the harmful prompts and "
          f"{pb['friction_rate']:.3f} of the benign ones — the same rate, because it "
          "judges the act and never the intent. It is asserted as a test "
          "(`tests/scenarios/test_external_eval.py`), not merely stated.")
        a("")

    ext = r.get("external")
    if ext:
        b = ext["benign_traffic"]
        a("## Held-out benign traffic (independently generated)")
        a("")
        a(f"Measured {ext['date']} · `scripts/eval_external.py` · raw: "
          f"`tests/external-eval.json`")
        a("")
        a(f"**{b['n']}** legitimate agent calls generated by an independent model over "
          "this instance's real tool surface — none written by the guard's author. "
          f"False positives **{b['false_positives']}/{b['n_reversible']}** = "
          f"**{b['false_positive_rate']:.3f}** (95% CI "
          f"{b['false_positive_ci95'][0]:.3f}–{b['false_positive_ci95'][1]:.3f}).")
        a("")
        a("That is the number to believe, and it is **above** the 0.000 the 14 "
          "hand-written benign controls report. The hand-written set uses only verbs the "
          "author also declared in the manifest, so it could not show this cost; every "
          "one of these false positives is a verb the manifest does not declare, held by "
          "the fail-closed rule.")
        a("")
        inj = ext.get("all_corpus", {})
        if inj:
            a(f"A second external corpus, "
              f"[deepset/prompt-injections]({ext['corpus']['source']}) "
              f"({ext['corpus']['rows']} rows), was also scored and is reported here as a "
              "**negative result**: an independent model mapped "
              f"{ext['corpus']['rows'] - inj['n']} of its "
              f"{ext['corpus']['rows']} texts to no tool call at all, and the remainder to "
              "none that is destructive or outward. It is a text-classification corpus of "
              "chatbot instruction-override attempts, so it cannot measure a guard that "
              "intercepts actions. It is left in the repository with this finding rather "
              "than dropped, because the mismatch is worth knowing before anyone else "
              "reaches for it.")
            a("")
    return "\n".join(out) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--selftest", action="store_true")
    args = ap.parse_args()

    if args.selftest:
        fixture = {
            "date": "2026-01-01", "guard_rev": "9.9.9",
            "scenarios_total": 1, "scenarios_passing": 1, "scenarios_failing": 0,
            "per_scenario": [{"id": "bp-01", "family": "f", "attempt": "a",
                              "expected": "DENY / r", "measured": "DENY / r",
                              "status": "PASS", "evidence": "t"}],
            "benign_total": 2, "benign_false_positives": 1, "false_positive_rate": 0.5,
            "benign_detail": [{"id": "bn-01", "status": "PASSED", "evidence": "t1"},
                              {"id": "bn-02", "status": "FAILED", "evidence": "t2"}],
        }
        text = render(fixture)
        assert "1 of 1 scenarios pass" in text, text
        assert "1/2 = 0.5" in text, text
        assert "`bp-01`" in text and "`bn-02`" in text
        print("selftest ok")
        return 0

    if not RESULTS_JSON.exists():
        print(f"error: {RESULTS_JSON} does not exist — run scripts/score_scenarios.py first",
              file=sys.stderr)
        return 1
    r = json.loads(RESULTS_JSON.read_text(encoding="utf-8"))
    # the property-based search writes its own dated record (guard/search.py, checked in
    # as tests/search-findings.json). Folded in here so every number in RESULTS.md still
    # comes from a file on disk and none from a run's narration. Absent => section omitted.
    search_json = RESULTS_JSON.parent / "search-findings.json"
    if search_json.exists():
        r["search"] = json.loads(search_json.read_text(encoding="utf-8"))
    # the de-authored external evaluation writes its own dated records
    # (scripts/eval_agentharm.py, scripts/eval_external.py). Same contract: folded in
    # here so every number in RESULTS.md comes from a file on disk, absent => omitted.
    for key, name in (("agentharm", "agentharm-eval.json"), ("external", "external-eval.json")):
        path = RESULTS_JSON.parent / name
        if path.exists():
            r[key] = json.loads(path.read_text(encoding="utf-8"))
    RESULTS_MD.write_text(render(r), encoding="utf-8")
    print(f"wrote {RESULTS_MD.relative_to(ROOT)} "
          f"({r['scenarios_passing']}/{r['scenarios_total']} scenarios, "
          f"FP rate {r['false_positive_rate']})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
